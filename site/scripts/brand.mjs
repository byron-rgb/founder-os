// Reads the founder's design system from the brain and writes src/styles/brand.css.
// Source: ../brain/3 Marketing/Brand/design-system.json (made by Brand Studio).
// No design system yet? Keeps a neutral starter brand so the site still builds.
import { readFileSync, writeFileSync, existsSync, mkdirSync, copyFileSync, lstatSync } from 'node:fs';
import { dirname, join, resolve, sep, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const brandDir = join(root, '..', 'brain', '3 Marketing', 'Brand');
const src = join(brandDir, 'design-system.json');
const out = join(root, 'src', 'styles', 'brand.css');

const starter = {
  name: 'Starter brand',
  colours: [
    { name: 'Ink', hex: '#17191E', use: 'text' },
    { name: 'Paper', hex: '#F6F6F4', use: 'background' },
    { name: 'Signal', hex: '#2F5BEA', use: 'accent, buttons' },
    { name: 'Mist', hex: '#E8E9EC', use: 'panels' },
  ],
  fonts: [
    { role: 'headline', family: 'Plus Jakarta Sans', weight: 700, source: 'Google Fonts' },
    { role: 'body', family: 'Inter', weight: 400, source: 'Google Fonts' },
  ],
  type: { headline: '44px', subhead: '26px', body: '17px', small: '14px' },
  spacing: ['8px', '16px', '24px', '48px'],
  corners: '8px',
  button: { background: 'Signal', text: 'Paper', corners: '8px' },
  logo: { main: null, dark: null },
};

let ds = starter, from = 'starter brand (no design-system.json yet)';
if (existsSync(src)) {
  try { ds = { ...starter, ...JSON.parse(readFileSync(src, 'utf8')) }; from = src; }
  catch (e) { console.warn(`brand: could not read design-system.json (${e.message}); using starter brand`); }
}

// Picks colours by what the design system says they're for. Words are tried in order,
// so "card" beats "panel" (dark panels would make text unreadable).
const byUse = (words, fallback) => {
  for (const w of words) {
    const c = ds.colours.find((c) => (c.use || '').toLowerCase().includes(w));
    if (c) return c.hex;
  }
  return (ds.colours[fallback] || ds.colours[0]).hex;
};
const colourOf = (v) => (!v ? null : String(v).startsWith('#') ? v : (ds.colours.find((c) => c.name === v) || {}).hex || null);
const fontOf = (prefix, fb) => (ds.fonts.find((f) => (f.role || '').toLowerCase().startsWith(prefix)) || {}).family || fb;
const px = (v, fb) => (v == null ? fb : typeof v === 'number' ? `${v}px` : v);
const sizes = ds.type || ds.typeSizes || {};
// Cards, photos and fields use the brand's corners; buttons can have their own (pill buttons stay off photos).
const cardCorners = typeof ds.corners === 'object' ? (ds.corners.radius ?? ds.corners.cards ?? ds.corners.card) : ds.corners;
const radius = px(cardCorners ?? ds.button?.radius ?? ds.button?.corners, '6px');
const radiusBtn = px(ds.button?.radius ?? ds.button?.corners ?? cardCorners, radius);

const text = byUse(['body text', 'text', 'ink'], 0);
const bg = byUse(['page background', 'background', 'page'], 1);
const accent = colourOf(ds.button?.background) || byUse(['accent', 'button'], 2);
const onAccent = colourOf(ds.button?.text) || bg;
const panel = byUse(['card', 'form', 'section', 'panel'], 3);
// Readability: accent-coloured small text must reach 4.5:1 on the page, else use the text colour.
const lum = (hex) => { const h = hex.replace('#', ''); const f = h.length === 3 ? h.split('').map((x) => x + x).join('') : h.slice(0, 6);
  const c = [0, 2, 4].map((i) => parseInt(f.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]; };
const contrast = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((m, n) => n - m); return (x + 0.05) / (y + 0.05); };
const accentText = contrast(accent, bg) >= 4.5 && contrast(accent, panel) >= 4.5 ? accent : text;
const head = fontOf('head', 'Georgia'), body = fontOf('body', 'system-ui');

const css = `/* Generated by scripts/brand.mjs from ${from === src ? 'brain/3 Marketing/Brand/design-system.json' : from}. Don't edit: change the design system and run npm run brand. */
:root {
  --c-text: ${text};
  --c-bg: ${bg};
  --c-accent: ${accent};
  --c-accent-text: ${accentText};
  --c-on-accent: ${onAccent};
  --c-panel: ${panel};
  --f-head: "${head}", Georgia, serif;
  --f-body: "${body}", system-ui, -apple-system, sans-serif;
  --t-h1: ${px(sizes.headline, '44px')};
  --t-h2: ${px(sizes.subhead, '26px')};
  --t-body: ${px(sizes.body, '17px')};
  --t-small: ${px(sizes.small, '14px')};
  --radius: ${radius};
  --radius-btn: ${radiusBtn};
  --s1: ${px(ds.spacing?.[0], '8px')}; --s2: ${px(ds.spacing?.[1], '16px')}; --s3: ${px(ds.spacing?.[2], '24px')}; --s4: ${px(ds.spacing?.[3], '48px')};
}
`;
writeFileSync(out, css);

// Google Fonts link for the layout
const gf = ds.fonts.filter((f) => /google/i.test(f.source || '')).map((f) => {
  const w = [...new Set([400, ...[].concat(f.weight || 600).map(Number)])].sort((x, y) => x - y).join(';');
  return `family=${encodeURIComponent(f.family).replace(/%20/g, '+')}:wght@${w}`;
});
writeFileSync(join(root, 'src', 'content', 'fonts.json'), JSON.stringify({ href: gf.length ? `https://fonts.googleapis.com/css2?${gf.join('&')}&display=swap` : null }, null, 2));

// Copy logos into public/ so pages can use them. Only image files that sit inside the
// Brand folder (no ../ paths, no shortcuts/symlinks pointing elsewhere).
mkdirSync(join(root, 'public', 'brand'), { recursive: true });
const IMG = new Set(['.png', '.jpg', '.jpeg', '.svg', '.webp']);
for (const key of ['main', 'dark']) {
  const rel = ds.logo?.[key];
  if (!rel || typeof rel !== 'string') continue;
  const p = resolve(brandDir, rel);
  const ext = extname(p).toLowerCase();
  if (!p.startsWith(resolve(brandDir) + sep) || !IMG.has(ext) || !existsSync(p) || lstatSync(p).isSymbolicLink()) {
    console.warn(`brand: skipped logo "${rel}" (must be an image inside the Brand folder)`);
    continue;
  }
  copyFileSync(p, join(root, 'public', 'brand', `logo-${key}${ext}`));
}
console.log(`brand: styles written from ${from === src ? 'your design system' : from}`);
